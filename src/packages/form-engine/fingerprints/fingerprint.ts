/**
 * Semantic fingerprints - stable identity for "the same question".
 * ---------------------------------------------------------------------------
 * Spec section 19 describes the product's main differentiator: correcting a
 * mapping ONCE should improve every future application. That requires answering
 * a hard question:
 *
 *     "Have I seen this question before?"
 *
 * across pages whose HTML has nothing in common. Greenhouse renders
 * `id="job_application_answers_attributes_3_text_value"`. Lever renders
 * `name="cards[abc123][field0]"`. Workday regenerates its ids on every render.
 * None of that is identity. What is stable is what the question SAYS.
 *
 * SO: A FINGERPRINT IS COMPUTED FROM MEANING, NOT FROM MARKUP.
 *
 * Included:  normalized label, control kind, normalized option labels.
 * Excluded:  DOM ids, CSS classes, DOM position, page URL, ATS name.
 *
 * The exclusions are the interesting half. Including the URL would make every
 * company a separate question and the learning system would never generalise.
 * Including a generated id would break the match on the very next page load.
 *
 * FOUR SCOPES, NOT ONE
 * A single fingerprint cannot express "this everywhere" and "this only at this
 * company". So we compute several, from broadest to narrowest, and the learning
 * store records which scope a correction applies at (spec section 19):
 *
 *     global     "Given name" means legalFirstName, everywhere
 *     ats        On Greenhouse, "Phone" means contact.phone
 *     company    At company.example, "Preferred hub" means preferredLocations
 *     exact      This precise question, on this precise form
 *
 * A narrower scope is a stronger claim and wins when several match.
 */
import { stableHashParts } from '@shared/ids';
import { normalizeLabel } from '../descriptor/normalize';
import type { ControlKind, FieldDescriptor } from '../descriptor/types';

/** The set of fingerprints computed for one field. */
export interface FieldFingerprints {
  /** Meaning only. Matches the same question on any site. */
  global: string;
  /** Meaning + ATS. Matches the same question on the same platform. */
  ats: string;
  /** Meaning + hostname. Matches the same question at the same company. */
  company: string;
  /** Meaning + hostname + structural detail. The narrowest claim. */
  exact: string;
}

/**
 * The semantic content of a field, before hashing.
 *
 * Exposed as a separate step because the debug panel and the mapping playground
 * need to SHOW why two fields did or did not match. A hash you cannot explain
 * is a hash you cannot debug, and fingerprint mismatches are exactly the kind
 * of bug that is otherwise invisible.
 */
export interface SemanticSignature {
  /** The best available human-readable description of the question. */
  question: string;
  /** Control kind, because "Country" as text and as select are different asks. */
  kind: ControlKind;
  /** Normalized, sorted option labels - the answer space of the question. */
  options: string[];
}

/**
 * Choose the text that best represents what the field is asking.
 *
 * Priority order, and why:
 *   1. label           - what the form author wrote for a human to read
 *   2. accessibleName  - the computed name; usually equals the label, and is
 *                        the correct fallback when the label is an aria-label
 *   3. nearbyText      - the question's prose when there is no real label
 *   4. placeholder     - weakest: often an EXAMPLE ("e.g. Jane") rather than a
 *                        question, so it is used only when nothing else exists
 *
 * `name`/`id` are deliberately NOT used. They are frequently autogenerated, and
 * a fingerprint built on them would change between two loads of the same form -
 * which would silently break every learned mapping.
 */
export function selectQuestionText(descriptor: FieldDescriptor): string {
  const candidates = [
    descriptor.label,
    descriptor.accessibleName,
    descriptor.nearbyText,
    descriptor.placeholder,
  ];

  for (const candidate of candidates) {
    const normalized = normalizeLabel(candidate);
    // Require two characters: a single stray character is noise, not a question.
    if (normalized.length > 1) return normalized;
  }
  return '';
}

/**
 * Reduce a descriptor to its semantic signature.
 *
 * Option labels are normalized and SORTED. Sorting matters: an ATS may render
 * ["Yes", "No"] or ["No", "Yes"] depending on locale or A/B test, and the
 * question is the same either way. Without sorting, the same question would
 * produce two different fingerprints and the learning system would have to be
 * taught twice.
 *
 * Options are also capped. A country dropdown has ~250 entries; hashing all of
 * them costs time on every field of every scan and adds no discriminating power
 * beyond the first several. The cap is a fixed constant, not a runtime-budget
 * knob, because a fingerprint MUST be identical on a 2 GB Chromebook and a 64 GB
 * workstation - deriving it from device capability would make learned mappings
 * fail to match across the user's own machines.
 */
const MAX_FINGERPRINTED_OPTIONS = 12;

export function computeSignature(descriptor: FieldDescriptor): SemanticSignature {
  const options = (descriptor.options ?? [])
    .map((option) => normalizeLabel(option.label))
    .filter((label) => label.length > 0)
    .sort()
    .slice(0, MAX_FINGERPRINTED_OPTIONS);

  return {
    question: selectQuestionText(descriptor),
    kind: descriptor.kind,
    options,
  };
}

/**
 * Compute all four scoped fingerprints for a field.
 *
 * Every hash is prefixed with its scope name so that a global and a company
 * fingerprint can never collide, even in the degenerate case where the
 * additional inputs are empty.
 */
export function computeFingerprints(descriptor: FieldDescriptor): FieldFingerprints {
  const signature = computeSignature(descriptor);
  const meaning = [signature.question, signature.kind, signature.options.join(',')];

  return {
    global: stableHashParts(['g', ...meaning]),

    ats: stableHashParts(['a', descriptor.ats, ...meaning]),

    company: stableHashParts(['c', descriptor.hostname, ...meaning]),

    // The exact scope adds the structural attributes the other scopes exclude.
    // Those attributes are unstable on some platforms, which is precisely why
    // this is the NARROWEST scope: when they happen to be stable (most
    // Greenhouse and Lever forms) it gives a very precise match, and when they
    // are not, the broader scopes still work. It fails safe by being ignored.
    exact: stableHashParts([
      'e',
      descriptor.hostname,
      descriptor.ats,
      descriptor.name,
      descriptor.autocomplete,
      ...meaning,
    ]),
  };
}

/**
 * The single fingerprint stored on a descriptor.
 *
 * The global scope, because it is the one that generalises: a correction learned
 * on one company's form should help on the next company's form. The narrower
 * scopes are computed on demand by the learning store when it needs them, so
 * every descriptor does not carry four hashes across the message boundary for a
 * feature most fields never use.
 */
export function computeSemanticFingerprint(
  descriptor: Omit<FieldDescriptor, 'semanticFingerprint'>,
): string {
  // The cast is safe and confined: computeFingerprints reads only the semantic
  // fields, never `semanticFingerprint` itself. Taking an Omit<> in the
  // signature is what lets the detector build a descriptor and then fill in its
  // own fingerprint without a partially-typed intermediate object.
  return computeFingerprints({ ...descriptor, semanticFingerprint: '' }).global;
}
